let currentLang = 'lt';
const LT_ORIGINAL = new Map();   // čia išsaugomi lietuviški tekstai iš index.html
const LT_ATTRS = new Map();

function t(key, vars = {}) {
  let s = (DYN[currentLang] && DYN[currentLang][key]) || DYN.lt[key] || key;
  Object.entries(vars).forEach(([k, v]) => { s = s.replace(`{${k}}`, v); });
  return s;
}

function applyLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'lt';
  document.documentElement.lang = currentLang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (!LT_ORIGINAL.has(el)) LT_ORIGINAL.set(el, el.innerHTML);
    const key = el.dataset.i18n;
    el.innerHTML = currentLang === 'en' && EN[key] ? EN[key] : LT_ORIGINAL.get(el);
  });

  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.dataset.i18nAttr.split(';').forEach(pair => {
      const [attr, key] = pair.split(':');
      const id = attr + '|' + key;
      if (!LT_ATTRS.has(el)) LT_ATTRS.set(el, {});
      const saved = LT_ATTRS.get(el);
      if (!(id in saved)) saved[id] = el.getAttribute(attr) || '';
      el.setAttribute(attr, currentLang === 'en' && EN[key] ? EN[key] : saved[id]);
    });
  });

  document.querySelectorAll('.lang-btn').forEach(b => {
    const on = b.dataset.lang === currentLang;
    b.classList.toggle('active', on);
    b.setAttribute('aria-pressed', on);
  });

  try { localStorage.setItem('augintimus-lang', currentLang); } catch (e) {}
  document.dispatchEvent(new CustomEvent('langchange'));
}

document.querySelectorAll('.lang-btn').forEach(b => {
  b.addEventListener('click', () => applyLang(b.dataset.lang));
});

// Pradinė kalba: ?lang=en nuorodoje > anksčiau pasirinkta > lietuvių
(function initLang() {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  let saved = null;
  try { saved = localStorage.getItem('augintimus-lang'); } catch (e) {}
  const lang = fromUrl || saved || 'lt';
  if (lang === 'en') applyLang('en');
})();
